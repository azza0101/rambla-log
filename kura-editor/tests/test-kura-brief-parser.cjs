'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const parse=require('../kura-brief-parser.js').parse;
const sample=fs.readFileSync(path.join(__dirname,'brief-novembre-v3.txt'),'utf8');
const result=parse(sample);
assert.equal(result.ok,true,JSON.stringify(result.errors));
assert.equal(result.count,3);
assert.deepEqual(result.pages.map(p=>p.fields.head1),[
 "Un calice tira l'altro","Maiorca senza spiagge","La savana cambia faccia"]);
assert.deepEqual(result.pages.map(p=>p.fields.label_highlight),Array(3).fill('Da non perdere'));
assert.equal(result.pages[0].fields.body1.includes('**Valle del Vipacco**'),true);
assert.equal(result.pages[0].meta.referenceSubtitle,'Vigne, borghi e orange wine');
assert.equal(result.pages[1].meta.referenceSubtitle,'Valldemossa e Serra de Tramuntana');
assert.equal(result.pages[2].meta.referenceSubtitle,'Quando la savana torna verde');
assert.equal(result.pages[0].meta.immagine.includes('Giulia'),true);
assert.equal(result.pages[0].meta.layout.includes('post-it'),true);
const expanded=sample+'\nDESTINAZIONE 4 — ITALIA · TORINO\nTITOLETTO 1: Titolo\nBODY1: Primo **paragrafo**.\nTITOLETTO 2: Secondo\nBODY2: Secondo paragrafo.\nPOST-IT:\nBase: Torino\nDurata: 2 giorni\nDa vivere: musei\nDa sapere: scarpe comode';
const many=parse(expanded);
assert.equal(many.ok,true);
assert.equal(many.count,4);
assert.equal(many.pages[3].fields.label_highlight,'Da vivere');
assert.equal(parse(sample.replace("BODY2: Parti per un **safari all'alba**","SCENARIO: Parti per un **safari all'alba**")).ok,false);
const escaped=sample.replace('**Valle del Vipacco**','\\*\\*Valle del Vipacco\\*\\*');
assert.equal(parse(escaped).pages[0].fields.body1.includes('**Valle del Vipacco**'),true);
const project=JSON.parse(fs.readFileSync(path.join(__dirname,'../projects/KURA_Progetto_Novembre_2026_MCP_TEST.json'),'utf8'));
assert.equal(project.pages.length,3);
assert.equal(new Set(project.pages.map(p=>p.imageKeys.scene)).size,3);
assert.equal(project.pages.every(p=>p.visuals.scene.visible),true);
assert.equal(project.pages.every((p,i)=>p.fields.body1===result.pages[i].fields.body1),true);
assert.equal(project.pages.every((p,i)=>p.meta.referenceSubtitle===result.pages[i].meta.referenceSubtitle),true);
console.log('KURA brief parser: tests passed (3+4 destinations, bold, metadata, validation and artwork)');
